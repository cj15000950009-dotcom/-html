/**
 * 生成内联 data: URI 的 SVG 默认占位头像。
 * 圆形背景用角色 themeColor 填充，叠加角色名首字（白色居中）。
 * 无外部依赖，离线可用。
 */
export function generateDefaultAvatar(name: string, themeColor: string): string {
  const initial = (name || '?').charAt(0);
  const color = themeColor || '#64748b';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="120" height="120" viewBox="0 0 120 120"><circle cx="60" cy="60" r="58" fill="${color}"/><text x="60" y="60" font-size="52" font-weight="bold" fill="white" text-anchor="middle" dominant-baseline="central" font-family="sans-serif">${initial}</text></svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

