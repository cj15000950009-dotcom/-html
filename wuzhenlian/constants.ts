/** 判断立绘库文件夹是否为允许的角色（user/主角、武侦连角色、或用户新建的 f_ 开头） */
export function isAllowedSpriteFolder(folder: CustomFolder): boolean {
    const n = (folder.name || '').trim().toLowerCase();
    const id = String(folder.id || '').trim().toLowerCase();
    const fixed = ['player', 'sunweidong', 'gaomeng', 'luozhenhai', 'qinzheng', 'heguodong',
        'linzhengping', 'shaokai', 'mengkai', 'maqiang', 'fangxiao'];
    if (fixed.includes(id)) return true;
    if (id.startsWith('f_')) return true;
    if (id.startsWith('collection_') || n.startsWith('合集')) return true;
    const allowed = ['user', '{{user}}', '主角', '玩家', '孙卫东', '高猛', '罗振海', '秦铮',
        '贺国栋', '林正平', '邵凯', '孟凯', '马强', '方啸'];
    return allowed.some(a => n === a.toLowerCase() || id === a.toLowerCase());
}

